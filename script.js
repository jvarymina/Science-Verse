function defaultState(definition) {
  const state = {};
  definition.controls.forEach((control) => {
    state[control.key] = control.value !== undefined
      ? control.value
      : control.type === "checkbox"
        ? false
        : control.type === "select"
          ? control.options[0][0]
          : control.min;
  });
  return state;
}

function renderControls(definition) {
  experimentControls.innerHTML = definition.controls.map((control) => {
    if (control.type === "select") {
      return `
        <div class="control-group">
          <label for="control-${control.key}">${escapeHTML(control.label)}</label>
          <div class="control-field"><select id="control-${control.key}" data-control="${control.key}">
            ${control.options.map(([value, label]) => `<option value="${value}">${escapeHTML(label)}</option>`).join("")}
          </select></div>
        </div>`;
    }

    if (control.type === "checkbox") {
      return `
        <div class="control-group">
          <label><input type="checkbox" data-control="${control.key}" ${labState[control.key] ? "checked" : ""}> ${escapeHTML(control.label)}</label>
          <p class="control-help">غيّر الاختيار ثم اضغط «نفّذ التجربة».</p>
        </div>`;
    }

    return `
      <div class="control-group">
        <label for="control-${control.key}">${escapeHTML(control.label)}</label>
        <div class="control-field">
          <input id="control-${control.key}" type="range" data-control="${control.key}" min="${control.min}" max="${control.max}" step="1" value="${labState[control.key]}">
          <div class="range-output"><span id="value-${control.key}">${labState[control.key]}</span> ${escapeHTML(control.unit || "")}</div>
        </div>
      </div>`;
  }).join("");

  definition.controls.forEach((control) => {
    const input = experimentControls.querySelector(`[data-control="${control.key}"]`);
    if (input && control.type === "select") input.value = labState[control.key];

    if (input && control.type === "range") {
      input.addEventListener("input", () => {
        const output = $(`#value-${control.key}`);
        if (output) output.textContent = input.value;
      });
    }
  });
}

function readControls() {
  if (!currentLab) return;
  experimentControls.querySelectorAll("[data-control]").forEach((input) => {
    labState[input.dataset.control] = input.type === "checkbox"
      ? input.checked
      : input.type === "range"
        ? Number(input.value)
        : input.value;
  });
}

function openLab(id) {
  currentLab = lessons.find((lesson) => lesson.id === Number(id));
  if (!currentLab) return;

  const definition = experimentDefinitions[currentLab.type];
  labState = defaultState(definition);
  $("#labTitle").textContent = `درس ${currentLab.id}: ${currentLab.title}`;
  $("#labIntro").textContent = currentLab.intro;
  conceptText.textContent = currentLab.concept;

  renderControls(definition);
  observationText.textContent = "جهّز أدواتك، غيّر الإعدادات، وبعدها اضغط «نفّذ التجربة».";
  experimentScene.innerHTML = "";
  renderScene(false);

  labWorkspace.classList.remove("hidden");
  labWorkspace.scrollIntoView({ behavior: "smooth", block: "start" });
}

